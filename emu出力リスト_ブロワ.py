def fill_flag_area_plotly(fig, flags,range_name ,fillcolor=None, linecolor=None,y_min = None ,y_max = None):
    flags = flags.copy()
    if y_min == None:
        y_min = 0
    if y_max == None:
        y_max = 1

    '''
    fig:plotly.graph_objects.Figure オブジェクト
    flags: indexが日時型のbool pandas.Series オブジェクト
    range_name: 凡例に表示する名前
    fillcolor: 塗りつぶしの色
    linecolor: 境界線の色
    '''
    assert flags.dtype == bool, 'flagsのdtypeがboolではありません。'  # bool型であるかチェック
    assert isinstance(flags.index, pd.DatetimeIndex), 'flagsのindexがDatetimeIndexではありません。' #indexのチェック

    # flagsがTrueからFalseに変わる場所を検出する
    #シフトした項目flags_shiftを作成。塗りはじめと塗り終わりのindexを取得する。
    flags_shift = flags.shift(1, fill_value = False)
    flags.iloc[-1] = False    #塗り終わりで終わるようにするため、データの最後はFalseにする。
    starts = flags[(flags == True) & (flags_shift == False)].index
    ends = flags[(flags == False) & (flags_shift == True)].index

    #凡例用のダミー線グラフ
    fig.add_trace(go.Scatter(
        x = [None], y = [None],#凡例だけ表示させたいので値はなし。
        mode = 'lines',
        line = dict(color = fillcolor, width=2),
        name = range_name  # 凡例に表示する名前
    ))

    #取得した塗り終わりと塗りはじめの期間を描画
    for start, end in zip(starts, ends):
        fig.add_shape(
            type = 'rect',#矩形を描画するために指定。
            x0 = start, #塗りはじめ
            x1 = end,   #塗り終わり
            y0 = y_min, y1 = y_max,  # Y軸の範囲。
            xref = 'x', yref='paper',  # X軸はデータの範囲、Y軸は全体 (0~1) とする
            fillcolor = fillcolor, #面の色
            line = dict(color = linecolor),#線の色
            opacity = 0.2,#透明度
        )
    return fig

