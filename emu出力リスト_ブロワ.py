#@title 相互相関 nanを無視し試算
def time_series_correlation_ignore_nan(df,column,shift_column,title,graph_show = True,lags = 180):
    '''
    データフレームから指定した2つの列（column と shift_column）の時系列をずらした場合の相互相関を計算し、結果をプロットします。
    column と ずらすshift_columnの相関をみる。
    相関が＋5の時は、現在のcolumnに対して5分未来のshift_columnの相関を見ている。
    相関が-5の時は、現在のcolumnに対して5分過去のshift_columnの相関を見ている。
    1日のデータごとに相関係数の試算を行う。その際nanは無視する。

    風量がどのくらい流量から遅れているのか見たい場合は、
    aを風量、bを流量にする。
    df: pandas DataFrame
        入力データ

    column_x: str
        相互相関の独立変数となる列名（風量など）
    shift_column: str
        相互相関の従属変数となる列名（流量など）
    lags:
        相互相関のラグを決定（単位は分）defaultは180分

    '''
    #データの準備
    data = df.copy()
    data['時間'] = data['時刻']
    data['日'] = data['日付']

    _data = data[[column,shift_column]].copy()
    # _data =  _data[(_data[shift_column].notna()) & (_data[column_x].notna())]# NANのままで標準化すると全てNANになってしまうため除去
    _data.loc[:,shift_column]=_data[shift_column].fillna(0)# NANのままで標準化すると全てNANになってしまうため
    _data.loc[:,column]=_data[column].fillna(0)# NANのままで標準化すると全てNANになってしまうため
    #標準化。
    data_std = stats.zscore(_data)
    data_std['日'] = data['日']
    data_std['時間'] = data['時間']
    #日付、時間を使いピポットテーブルを作成する。
    #間が飛んでいるデータがあるときは、nanに、日付ごとに相互相関をしてくれるため、時刻が飛躍しているデータどうしで相互相関をとることはない。


    time_data_std = pd.pivot_table(data_std,
                            index = data_std['時間'],
                            columns = data_std['日'],
                            values  = column)

    time_data_r_std = pd.pivot_table(data_std,
                            index = data_std['時間'],
                            columns = data_std['日'],
                            values = shift_column)

    #5分データなので5で割る。行数の文だけforで算出
    lags_range = range(-int(lags/5), int(lags/5) + 1)
    df_xc_all_list = []#結果保存用


    nan_list= [np.nan] * len(lags_range) #nanデータ格納用リスト
    for i in range(1,len(time_data_std.columns)): #
        a = time_data_std.iloc[:,i].copy()
        b = time_data_r_std.iloc[:,i].copy()
        c = time_data_std.columns[i]
        cross_correlations = [] #1日のラグ係数格納用　1日計算後リセットする。
        if a.notna().sum() > 36:  # aのデータに有効なデータが36ポイント(3時間)以上あれば計算
            for lag in lags_range: # シフトし、計算。変数rag_rangeの分だけ aとNだけずらしたbの相関を見る。
                shifted_b = b.shift(lag)
                valid_idx = a.notna() & shifted_b.notna()
                if valid_idx.sum() > 36:  # 有効なデータが36ポイント(3時間)以上あれば計算
                    corr = a[valid_idx].corr(shifted_b[valid_idx])
                else:
                    corr = np.nan  # データポイントが少なければ NaN とする
                cross_correlations.append(corr)
        else:#有効なデータが1時間ない場合は、全てnanを入れたデータを保存
            cross_correlations = nan_list
        df_xc_all_list.append(pd.Series(cross_correlations,name=c)) #1日の結果をシリーズ化しリストへ格納（データフレームより軽い。）
    df_xc_all = pd.concat(df_xc_all_list,axis=1)#リストを結合　全データを一つのデータフレーム化


    #対象データ数（日）の確認
    count_no_nan_columns = df_xc_all.columns[df_xc_all.isna().sum() == 0].size

    print(f'{column}に対する{shift_column}の遅れ時間試算')
    print(f'全データ日数:{len(df_xc_all.columns)}日')
    print(f'全データ日数:{count_no_nan_columns}日')

    #indexをラグに変更
    lists =list(range(-lags , lags+5 , 5))
    # lists =list(range(-23,24,1))　#1hデータ
    df_xc_all['lag'] = lists#わかりやすいように、負の値なら、過去、正なら未来の値の相関とする。
    df_xc_all['lag'] = df_xc_all['lag'] * -1#わかりやすいように、負の値なら、過去、正なら未来の値の相関とする。

    df_xc_all = df_xc_all.set_index('lag')
    df_xc_all = df_xc_all.sort_index()

    if graph_show == True:
        df_xc_all.plot(legend=False)
        plt.rcParams['figure.figsize'] = (19, 6)
        plt.ylabel('相関係数')
        plt.xlabel('Lag(hr)')
        plt.xticks(lists)
        plt.show()

        df_xc_all.T.plot.box(showmeans=True)
        plt.tight_layout()
        plt.rcParams['figure.figsize'] = (16, 6)
        plt.rcParams['font.size'] = 14
        plt.ylabel('相関係数')
        plt.xlabel('時間のずれ[hr]', rotation=90)
        plt.ylim([-1,1])
        plt.title(title)
    return df_xc_all

