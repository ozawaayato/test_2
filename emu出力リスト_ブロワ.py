#@title ヒストグラムを作成　plot_histogram
def plot_histogram(df, column, title, x_axis_name, y_axis_name, nbins,data_min = False, data_max = False):
    """
    指定されたデータフレームの特定の列のヒストグラムを作成し表示する関数。
    パラメータ:
    df : pandas.DataFrame
        ヒストグラムを作成するデータフレーム。
    column : str
        ヒストグラムを作成するデータフレーム内の列名。
    title : str
        グラフのタイトル。
    x_axis_name : str
        X軸のラベル。
    y_axis_name : str
        Y軸のラベル。
    nbins : int
        ヒストグラムのビンの数。
        data_min : float, optional
        ヒストグラムのデータの最小値。デフォルトはFalse。
    data_max : float, optional
        ヒストグラムのデータの最大値。デフォルトはFalse。
    """
    # ヒストグラムのデータを準備。NaN値を削除し、値が0より大きいものだけを抽出。
    data = df[df[column] > 0][column].dropna()
    # ヒストグラムの作成
    fig = go.Figure(data=[go.Histogram(
        x=data,
        nbinsx=nbins,  # ビンの数を指定
        marker_color='blue',  # ビンの色を設定
        opacity=0.75  # 不透明度の設定
    )])
    if data_min == False:
        data_min = data.min()
    if data_max == False:
        data_max = data.max()

    # グラフのレイアウトを設定
    # レイアウトの設定
    fig.update_layout(
        title=title,  # グラフタイトル
        xaxis_title=x_axis_name,  # X軸のタイトル
        yaxis_title=y_axis_name,  # Y軸のタイトル
        font=dict(size=18),  # フォントサイズの設定
        xaxis=dict(range=[data_min, data_max]) #最大値と最小値を決定
    )
    # プロットの表示
    fig.show()

#@title 相関関数を表すグラフの表示、相関係数の算出 plot_single_correlation

def plot_single_correlation(df, column_x, column_y,column_x_name,column_y_name,title, x_lim = [None,None],y_lim = [None,None],method='pearson'):
    '''
    2つの列の相関係数を計算し、散布図を表示する関数。

    Parameters:
    df (DataFrame): データフレーム
    column_x (str): X軸に使用するカラム名
    column_y (str): Y軸に使用するカラム名
    method (str): 相関係数の計算方法。'pearson', 'spearman', 'kendall' のいずれか
    Returns:
    corr_value (float): 計算された相関係数
    '''
    # 欠損値を削除
    df_clean = df[[column_x, column_y]].dropna().copy()
    # 相関係数の計算
    if method == 'pearson':
        corr_value, _ = pearsonr(df_clean[column_x], df_clean[column_y])
    elif method == 'spearman':
        corr_value = df_clean[column_x].corr(df_clean[column_y], method='spearman')
    elif method == 'kendall':
        corr_value = df_clean[column_x].corr(df_clean[column_y], method='kendall')
    else:
        raise ValueError("methodは 'pearson', 'spearman', 'kendall' のいずれかを指定してください。")
    # 相関係数を表示
    print(f'{method.capitalize()}相関係数 between {column_x} and {column_y}: {corr_value:.3f}')

    # 散布図の作成
    plt.figure(figsize=(10, 6))
    plt.scatter(df[column_x] ,df[column_y], s=32, alpha=.8)
    plt.gca().spines[['top', 'right']].set_visible(False)

    # 近似直線の計算
    X = df_clean[column_x].values.reshape(-1, 1)
    Y = df_clean[column_y].values.reshape(-1, 1)
    model = LinearRegression()
    model.fit(X, Y)
    Y_pred = model.predict(X)

    # 回帰係数と切片を取得
    slope = model.coef_[0][0]
    intercept = model.intercept_[0]

    # 近似線をプロット
    plt.plot(df_clean[column_x], Y_pred, color='red', linewidth=2, label=f'y = {slope:.3f}x + {intercept:.3f}\n相関係数R = {corr_value:.3f}')
    plt.xlabel(column_x_name,fontsize=20)
    plt.ylabel(column_y_name,fontsize=20)
    plt.title(title,fontsize=25)
    plt.tick_params(axis='both', which='major', labelsize=15)
    plt.legend()
    # X軸とY軸の範囲を設定
    if x_lim[0] != None and y_lim[0] != None:
        plt.xlim(x_lim[0],x_lim[1])  # X軸の範囲を設定
        plt.ylim(y_lim[0],y_lim[1]) # Y軸の範囲を設定

    plt.grid(True)

