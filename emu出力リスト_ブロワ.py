#@title 単、重回帰モデル式作成　create_model
#単回帰、重回帰のモデル式作成、及び実測値_予測値グラフの表示
#正規化させる場合はnormalize = Trueとする。（デフォルトはFalse）decimal_places は小数点をどこまで見せる化を決定
def create_model(df,list_column_x,column_y,column_x_name,column_y_name,title,explanatory_name = [False],predictor_name = False,x_lim  = [None,None],y_lim  = [None,None],normalize = False,decimal_places = 3):

    '''
    単回帰または重回帰モデルを作成し、実測値と予測値の散布図を描画する関数。

    df : pandas.DataFrame
        回帰モデルの作成に使用するデータを含むデータフレーム。
    list_column_x : list of str
        説明変数（X）として使用するカラム名のリスト。
    column_y : str
        目的変数（Y）として使用するカラム名。
    column_x_name : str
        グラフのX軸ラベルとして表示するテキスト。
    column_y_name : str
        グラフのY軸ラベルとして表示するテキスト。
    title : str
        グラフのタイトル。
    explanatory_name : list of str, optional
        説明変数の表示名。デフォルトは [False] で、指定がなければカラム名が使用される。
    predictor_name : str, optional
        予測値の表示名。デフォルトは False で、指定がなければカラム名が使用される。
    x_lim : list, optional
        X軸の表示範囲を指定するリスト [min, max]。デフォルトは [None, None]。
    y_lim : list, optional
        Y軸の表示範囲を指定するリスト [min, max]。デフォルトは [None, None]。
    normalize : bool, optional
        データの正規化を行うかどうかを指定。デフォルトは False。
    decimal_places : int, optional
        回帰係数と切片の小数点以下の表示桁数を指定。デフォルトは 3。

    Returns:
    X_model_test_random: テストデータに予測値と実測値を含めたデータフレーム
    coeff: 回帰係数と切片を含むリスト
    '''
    #0、nanデータを除外する。
    df = df[df[column_y] > 0]
    for i in list_column_x:
        df = df[df[i] > 0]

    #normalizeがTrueの時は、各説明、目的変数に使われるデータの最小値と最大値を用いて正規化を行う。
    if normalize == True:
        for i in list_column_x:
            df[i] = MinMaxScaler(df[i])
        df[column_y] = MinMaxScaler(df[column_y])

    #データフレームを説明変数と目的変数のみに分ける。
    X = df[list_column_x].astype(float).reset_index(drop=True)
    Y = df[column_y].astype(float).reset_index(drop=True)

    #学習期間とテストデータに分ける。分割割合3:7
    X_model_train_random, X_model_test_random = train_test_split(X, test_size=0.30, random_state = 42)
    Y_model_train_random, Y_model_test_random = train_test_split(Y, test_size=0.30, random_state = 42)

    #近似式の係数の計算
    #決定係数
    model = LinearRegression()
    #学習期間のデータを用いてモデルの作成
    model.fit(X_model_train_random,Y_model_train_random)
    # model.fit(X_test,y_test)
    #学習期間、テスト期間でそれぞれ評価
    print('全期間の決定係数',model.score(X,Y))
    print('\n学習期間内の決定係数',model.score(X_model_train_random,Y_model_train_random))
    print('test期間内の決定係数',model.score(X_model_test_random,Y_model_test_random))
    print('回帰係数\n{}'.format(pd.Series(model.coef_, index=X_model_test_random.columns)))
    print('切片: {}'.format(model.intercept_))
    X_model_test_random['予測値'] =  model.predict(X_model_test_random)
    X_model_test_random['実測値'] = Y_model_test_random

    #係数と切片をリスト化し格納
    coeff = list(model.coef_)
    coeff.append(model.intercept_)


    # 散布図の作成
    plt.figure(figsize=(10, 6))
    plt.scatter(X_model_test_random['実測値'],X_model_test_random['予測値'], s=32, alpha=.8)
    plt.gca().spines[['top', 'right']].set_visible(False)

    # # 切片0の直線近似線を計算
    x = X_model_test_random['実測値'].to_numpy()
    y = X_model_test_random['予測値'].to_numpy()
    slope, _, _, _ = np.linalg.lstsq(x[:, np.newaxis], y, rcond=None)

    # モデル式に使う係数を用いて近似直線のｙを計算
    y_pred = slope * x

    # 実測値と予測値のR²を計算
    r2 = r2_score(x, y)

    #explanatory_nameとpredictor_nameに値が入ってるとき、
    #model_nameに、グラフ上に記載するモデル式の文字列を作成
    #$x_{i+1}$ ：グラフ上で文字を小文字にする
    model_name = ''
    if explanatory_name[0] != False and predictor_name != False:
        for i in range(len(explanatory_name)):
            model_name = model_name + f'$x_{i+1}$:{explanatory_name[i]}\n'
        model_name = model_name + f'y  :{predictor_name}'


    #equationにグラフ上に記載する回帰式を入れる文字列を作成
    #{decimal_places}f  小数点第何位まで表示するかを
    equation = 'y = '
    for i in range(len(coeff)-1):
        equation = equation + f'{coeff[i]:.{decimal_places}f} $x_{i+1}$ + '
    equation = equation + f'{coeff[-1]:.{decimal_places}f}' #切片を入れる


    # 近似線をプロット
    plt.plot(x, y_pred, color='red', linewidth=2, label= '実測値と予測値の近似曲線')
    # plt.annotate(f'決定係数R² = {r2:.3f}\nモデル式:{equation}', xy=(0.01, 0.8), xycoords='axes fraction', fontsize=12, ha='left', color='black')
    # plt.annotate(f'{model_name}', xy=(0.01, 0.60), xycoords='axes fraction', fontsize=12, ha='left', color='black')
    #プロットとかぶった時ように、背景を0　透明度を指定
    plt.annotate(
        f'決定係数R² = {r2:.3f}\nモデル式:{equation}',
        xy=(0.02, 0.8),
        xycoords='axes fraction',
        fontsize=12,
        ha='left',
        color='black',
        bbox=dict(facecolor='white', edgecolor='white', boxstyle='round,pad=0.5', alpha=0.6)  # 背景白, 枠線黒
    )

    plt.annotate(
        f'{model_name}',
        xy=(0.02, 0.5),
        xycoords='axes fraction',
        fontsize=12,
        ha='left',
        color='black',
        bbox=dict(facecolor='white', edgecolor='white', boxstyle='round,pad=0.5', alpha=0.6)  # 背景白, 枠線黒
    )

    plt.xlabel(column_x_name,fontsize=20)
    plt.ylabel(column_y_name,fontsize=20)
    plt.title(title,fontsize=25)
    plt.tick_params(axis='both', which='major', labelsize=15)
    plt.legend()
    # X軸とY軸の範囲を設定
    if x_lim[0] != None and y_lim[0] != None:
        plt.xlim(x_lim[0], x_lim[1])  # X軸の範囲を 0 から 6 までに設定
        plt.ylim(y_lim[0], y_lim[1]) # Y軸の範囲を 0 から 12 までに設定

    plt.grid(True)

    # 近似線の式とR²を表示
    print(f'R²: {r2:.3f}')

    return coeff

#@title　正規化　MinMaxScaler
def MinMaxScaler(data ,data_min = False,data_max = False):
    '''
    Min-Maxスケーリングを行う関数。
    この関数は、与えられたデータをMin-Maxスケーリングして、0から1の範囲に正規化します。
    スケーリングの計算式は次の通りでデータの最小値と最大値を利用する。簡略的に計算。
    scaled_data = (data - data_min) / (data_max - data_min)

    Parameters:
    data (float or array-like): スケーリングしたいデータ。
    data_max (float, optional): データの最大値。デフォルトはFalse。
    data_min (float, optional): データの最小値。デフォルトはFalse。
    Returns:
    scaled_data (float or array-like): 0から1の範囲にスケーリングされたデータ。
    '''
    if data_max == False :
        data_max = data.max()
    if data_min == False:
        data_min = data.min()
    numerator = data - data_min
    denominator = data_max - data_min
    return numerator / (denominator)

#@title 発生待ち時間計算

def waiting_time(df,column_target):
    '''
    対象となるseriesデータが0超えになるまでの経過時間を算出。
    Parameters:
    df (DataFrame): データフレーム
    column_time,column_target: 待ち時間計算の対象となるカラム名

    Returns:
    waiting_time: 待ち時間のseriesデータ
    '''
    waiting_time = df.apply(lambda x: x['日時'] if x[column_target] > 0 else np.nan, axis=1)
    waiting_time = waiting_time.bfill()
    waiting_time=  waiting_time - df['日時']

    return waiting_time

#@title 経過時間計算

def elapsed_time(df,column_target):
    '''
    対象となるseriesデータが0超になった後の経過時間を算出。
    Parameters:
    df (DataFrame): データフレーム
    column_time,column_target: 経過時間計算の対象となるカラム名

    Returns:
    elapsed_time: 経過時間seriesデータ
    '''
    elapsed_time = df.apply(lambda x: x['日時'] if x[column_target] > 0 else np.nan, axis=1)
    elapsed_time = elapsed_time.ffill()
    elapsed_time=  df['日時'] - elapsed_time

    return elapsed_time

